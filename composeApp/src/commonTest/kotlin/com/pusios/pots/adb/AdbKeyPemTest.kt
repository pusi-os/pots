package com.pusios.pots.adb

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

/**
 * `adbkey` is the file the identity lives in. It is written once and read on every launch, so a
 * parser that loses the certificate or the key would silently regenerate the identity and make every
 * paired device ask to be authorized again.
 */
class AdbKeyPemTest {

    private val certificateHeader = "-----BEGIN CERTIFICATE-----"

    @Test
    fun `format and split round-trip both blocks`() {
        val pem = AdbKeyPem.format("cHJpdmF0ZQ==", "Y2VydGlmaWNhdGU=")
        val parts = AdbKeyPem.split(pem)

        assertEquals("cHJpdmF0ZQ==", parts?.privateKeyBase64)
        assertEquals("Y2VydGlmaWNhdGU=", parts?.certificateBase64)
    }

    @Test
    fun `long bodies are wrapped and still read back intact`() {
        val body = "A".repeat(400)
        val parts = AdbKeyPem.split(AdbKeyPem.format(body, body))

        assertEquals(body, parts?.privateKeyBase64)
        assertEquals(body, parts?.certificateBase64)
    }

    @Test
    fun `windows line endings and surrounding junk do not matter`() {
        val pem = "generated by pots\n" + AdbKeyPem.format("cHJpdmF0ZQ==", "Y2VydA==") + "\n\n"
        val parts = AdbKeyPem.split(pem.replace("\n", "\r\n"))

        assertEquals("cHJpdmF0ZQ==", parts?.privateKeyBase64)
        assertEquals("Y2VydA==", parts?.certificateBase64)
    }

    @Test
    fun `a missing certificate is a parse failure`() {
        val pem = AdbKeyPem.format("cHJpdmF0ZQ==", "Y2VydA==")
        assertNull(AdbKeyPem.split(pem.substringBefore(certificateHeader)))
    }

    @Test
    fun `an empty body is a parse failure`() {
        assertNull(AdbKeyPem.split(AdbKeyPem.format("", "Y2VydA==")))
    }

    @Test
    fun `unrelated text is a parse failure`() {
        assertNull(AdbKeyPem.split("nothing to see here"))
    }
}
